def apply_icons(cards):
    for (cid, i) in ICONS:
        card = next((c for c in CARDS + KID_CARDS if c["id"] == cid), None)
        assert card and i < len(card["steps"]), (cid, i)
    known = {f[5:-4] for f in os.listdir(os.path.join(os.path.dirname(__file__), "..", "..", "app", "src", "main", "res", "drawable")) if f.startswith("pict_")}
    for c in cards:
        for i, st in enumerate(c["steps"]):
            icon = ICONS.get((c["id"], i))
            if icon:
                assert icon in known, icon
                st["icon"] = icon

if __name__ == "__main__":
    apply_icons(CARDS)
    apply_icons(KID_CARDS)
    out = os.path.join(os.path.dirname(__file__), "..", "..", "content", "src", "main", "assets", "cards.json")
    for c in CARDS:
        assert c["call"] in ("", "101", "102", "103", "104", "112"), c["id"]
        assert 1 <= len(c["steps"]) <= 8, c["id"]
        for s in c["steps"]:
            assert len(s["action"]) <= 200, (c["id"], len(s["action"]), s["action"])
            # 27/9/3: about 27 words a step for a reader under stress
            assert len(re.findall(r"[\w'’]+", s["action"])) <= 27, (c["id"], s["action"])
    with open(out, "w", encoding="utf-8") as f:
        json.dump(CARDS, f, ensure_ascii=False, indent=1)
        f.write("\n")
    for c in KID_CARDS:
        assert c["id"].startswith("kid-") and c["call"] in ("", "112"), c["id"]
        assert 1 <= len(c["steps"]) <= 5, c["id"]
        for s in c["steps"]:
            # A young child: at most 15 words a step
            assert len(re.findall(r"[\w'’]+", s["action"])) <= 15, (c["id"], s["action"])
    with open(out.replace("cards.json", "kid_cards.json"), "w", encoding="utf-8") as f:
        json.dump(KID_CARDS, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(len(CARDS), "cards,", len(KID_CARDS), "for children")
