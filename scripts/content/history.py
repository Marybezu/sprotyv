def words(s):
    return len(re.findall(r"[\w'’-]+", s))


def main():
    ids = [s["id"] for s in STORIES]
    if len(ids) != len(set(ids)):
        sys.exit("Ids repeat")
    out = []
    for s in STORIES:
        if s["kind"] not in ("stood", "lost", "word", "summary"):
            sys.exit(f"{s['id']}: kind")
        if s["kind"] != "summary" and not s["sources"]:
            sys.exit(f"{s['id']}: no source")
        # One screen: short parts
        for k in ("happened", "outcome"):
            if words(s[k]) > 75:
                sys.exit(f"{s['id']}.{k}: {words(s[k])} words")
        if words(s["lesson"]) > 30:
            sys.exit(f"{s['id']}.lesson too long")
        for _, url in s["sources"]:
            if not url.startswith(("https://", "http://")) or "t.me" in url or "telegram" in url:
                sys.exit(f"{s['id']}: source url")
        out.append({**s, "sources": [{"title": t, "url": u} for t, u in s["sources"]], "checked": CHECKED})
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({"title": "Навіщо спротив", "stories": out}, f, ensure_ascii=False, separators=(",", ":"))
        f.write("\n")
    print(f"History: {len(out)} stories")


if __name__ == "__main__":
    main()
